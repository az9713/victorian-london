"""Asset 5: sack-pile — sandbox/assets/models/sacks.glb
ROUND 7 — TECHNIQUE CHANGE (sanctioned, blender/fixlists/B1-r7.md). Six rounds
of procedural ring-generator bodies failed with a different symptom every
time ("rod" -> "beak" -> "worm" -> "corrugated tube") because a lathe-style
radius function produces rotationally regular geometry BY CONSTRUCTION. This
round stops generating cloth and SIMULATES it: each sack is built as (1) a
lumpy rounded-box CONTENTS collision body, (2) a plain quad-tube CLOTH
envelope around it with the shoulder-and-outward region (t>=SHOULDER_T --
the collar/flare/tied end, all PASSING since round 5) pinned rigid, (3) a
ground collision plane. The cloth solver is stepped frame-by-frame
(`scene.frame_set`) -- NOT `bpy.ops.ptcache.bake*`, which needs a viewport
context and fails headless -- and the settled, deformed mesh is snapshotted
via `evaluated_get()` + `bpy.data.meshes.new_from_object()`. Sacks are
simmed SEQUENTIALLY (1, then 2 against baked-1, then 3 dropped across both)
so cloth-vs-cloth contact is really cloth-vs-baked-static-collision, which is
far more stable headless than three live cloth bodies colliding with each
other.

The neck (t>1: pinch, cord-wrap collar, flare, tied end) is generated by the
EXACT SAME `ring_profile` formula the round-5/6 manifests already passed --
copied byte-for-byte except for the deleted FOLDS/PUCKERS/scallop/rectness
machinery, none of which touched the neck branch anyway. Pinning verifies
itself: pinned-vertex world coordinates are diffed before/after the bake and
the max delta is printed and asserted near zero.
"""
